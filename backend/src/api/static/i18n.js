let LANG = localStorage.getItem("karta_lang")
  || ((navigator.language || "ru").toLowerCase().startsWith("ru") ? "ru" : "en");

function t(key, vars) {
  const dict = I18N[LANG] || I18N.ru;
  let text = dict[key] !== undefined ? dict[key] : (I18N.ru[key] !== undefined ? I18N.ru[key] : key);
  if (vars) {
    Object.keys(vars).forEach((name) => {
      text = text.split("{" + name + "}").join(String(vars[name]));
    });
  }
  return text;
}

function applyI18n(root) {
  const scope = root || document;
  scope.querySelectorAll("[data-i18n]").forEach((node) => { node.textContent = t(node.dataset.i18n); });
  scope.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    node.placeholder = t(node.dataset.i18nPlaceholder);
  });
  document.documentElement.lang = LANG;
  document.title = t("app.title");
  const button = document.getElementById("lang-btn");
  if (button) button.textContent = LANG === "ru" ? "EN" : "RU";
}

function toggleLang() {
  LANG = LANG === "ru" ? "en" : "ru";
  localStorage.setItem("karta_lang", LANG);
  applyI18n();
  if (typeof onLangChanged === "function") onLangChanged();
}
